def derive_model(defs, res):
    model = {}

    def absorb(c, owner, owner_id):
        rt = c["resource"]
        if rt not in RESOURCES:
            raise DefinitionError(f"{owner}: resource {rt} has no generated profile (supported: {', '.join(RESOURCES)})")
        m = model.setdefault(rt, dict(ods=[], vss=[], codes=[], elements=[], kpis=[]))
        ods, vss, codes = code_sources(c)
        for code in codes:
            if code not in m["codes"]:
                m["codes"].append(code)
        a_vss, a_codes = answer_sources(c)
        for o in ods:
            res.od(o)
            if o not in m["ods"]:
                m["ods"].append(o)
            if a_vss or a_codes:  # answers a criterion adds to this measurement
                a = res.answers.setdefault(o, dict(vss=[], codes=[]))
                for v in a_vss:
                    res.vs_url(v)
                    if v not in a["vss"]:
                        a["vss"].append(v)
                for code in a_codes:
                    if code not in a["codes"]:
                        a["codes"].append(code)
        for v in vss:
            res.vs_url(v)
            if v not in m["vss"]:
                m["vss"].append(v)
        for e in c.get("element", []):
            if e not in RESOURCES[rt]["elements"]:
                raise DefinitionError(f"{owner}: '{e}' is not a top-level element of {rt}")
            if e not in m["elements"]:
                m["elements"].append(e)
        if owner_id not in m["kpis"]:
            m["kpis"].append(owner_id)

    for kpi in defs["kpi"].values():
        for c in kpi["criteria"]:
            absorb(c, f"KPI '{kpi['id']}'", kpi["id"])
    for ds in defs["dataset"].values():  # data a dataset releases outside any KPI
        for c in ds.get("include", []):
            absorb(c, f"Dataset '{ds['id']}'", ds["id"])
    return model


def vs_label(res, vs_id):
    """Short display name for a ValueSet reference: the registry key when there is one."""
    if is_url(vs_id):
        for k, e in res.external.items():
            if unpinned(e["canonical"]) == unpinned(vs_id):
                return k
    return vs_id


def od_title(od):
    return od.get("preferredReportName") or od["code"]["coding"][0].get("display", od["id"])


def component_ods(defs, od):
    out = []
    for ext in od.get("extension", []):
        if ext.get("url", "").endswith("/" + OD_COMPONENT_EXT):
            out.append(ext["valueReference"]["reference"].split("/")[-1])
    return out


def fhirpath_code_match(cc):
    parts = [f"system='{c['system']}' and code='{c['code']}'" for c in cc["coding"]]
    if len(parts) > 1:
        parts = [f"({p})" for p in parts]
    return "code.coding.where(" + " or ".join(parts) + ").exists()"


def od_invariant(od_id, res):
    """The one invariant a generated profile derives from an ObservationDefinition."""
    od = res.od(od_id)
    when = fhirpath_code_match(od["code"])
    comps = component_ods(res.defs, od)
    if comps:
        checks = ["value.empty()"]
        for cid in comps:
            c = res.od(cid)
            match = fhirpath_code_match(c["code"])
            sel = f"component.where({match})"
            unit = c.get("quantitativeDetails", {}).get("unit")
            cond = "value.ofType(Quantity).exists()"
            if unit:
                u = unit["coding"][0]
                cond += f" and value.ofType(Quantity).system='{u['system']}' and value.ofType(Quantity).code='{u['code']}'"
            checks.append(f"{sel}.where({cond}).count() = 1")
        return when, " and ".join(checks), "panel with components: no value[x]; each component carries its quantity and unit"
    types = od.get("permittedDataType", [])
    if "Quantity" in types:
        unit = od.get("quantitativeDetails", {}).get("unit")
        cond = ["value.ofType(Quantity).exists()"]
        desc = "value[x] is a Quantity"
        if unit:
            u = unit["coding"][0]
            cond += [f"value.ofType(Quantity).system='{u['system']}'", f"value.ofType(Quantity).code='{u['code']}'"]
            desc += f" in {u['code']}"
        return when, " and ".join(cond), desc
    if "CodeableConcept" in types:
        cond = ["value.ofType(CodeableConcept).exists()"]
        desc = "value[x] is a CodeableConcept"
        vs_id = vs_ref_id(od)
        if od_id in res.answers:  # KPIs add answers: the permitted set is the generated union
            cond.append(f"value.ofType(CodeableConcept).memberOf('{res.canonical}/ValueSet/{answer_vs_id(od_id)}')")
            desc += f" from {answer_vs_id(od_id)}"
        elif vs_id:
            cond.append(f"value.ofType(CodeableConcept).memberOf('{res.vs_url(vs_id)}')")
            desc += f" from {vs_label(res, vs_id)}"
        return when, " and ".join(cond), desc
    if types:
        t = types[0]
        return when, f"value.ofType({t}).exists()", f"value[x] is a {t}"
    return when, "value.exists()", "value[x] is present"


