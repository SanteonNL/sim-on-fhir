def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen_model_fsh(defs, res, model):
    L = [f"// {HEADER}", ""]
    for rt, m in model.items():
        cfg = RESOURCES[rt]
        L += ["// " + "-" * 69, f"// {rt}", "// " + "-" * 69, ""]
        if cfg["code"]:
            L += [f"ValueSet: {code_vs_name(rt)}", f"Id: {code_vs_id(rt)}",
                  f'Title: "{rt} code (SAN KPI)"',
                  f'Description: "Every code a KPI definition asks for on {rt}. The union of the ObservationDefinition codes and the value sets referenced by the {rt} criteria of all KPI definitions."',
                  "* ^status = #draft", "* ^experimental = false"]
            for o in m["ods"]:
                for c in res.od(o)["code"]["coding"]:
                    L.append(f"* {c['system']}#{c['code']} {q(c.get('display', c['code']))}")
            for system, code in m["codes"]:
                L.append(f"* {system}#{code}")
            for v in m["vss"]:
                L.append(f"* include codes from valueset {res.vs_url(v)}")
            L.append("")

        invs = []
        if rt == "Observation":
            for o, a in res.answers.items():
                od = res.od(o)
                L += [f"ValueSet: {re.sub('[^A-Za-z0-9]', '', 'Answers-' + o.title() + '-SanKpi')}", f"Id: {answer_vs_id(o)}",
                      f'Title: "Answers: {od_title(od)} (SAN KPI)"',
                      f'Description: "Permitted coded answers for {od_title(od)}: the ObservationDefinition\'s own valid value set (when it has one) together with the answers KPI definitions list inline or by value set."',
                      "* ^status = #draft", "* ^experimental = false"]
                if vs_ref_id(od):
                    L.append(f"* include codes from valueset {res.vs_url(vs_ref_id(od))}")
                L += [f"* {system}#{code}" for system, code in a["codes"]]
                L += [f"* include codes from valueset {res.vs_url(v)}" for v in a["vss"]]
                L.append("")
            for o in m["ods"]:
                invs.append((f"{profile_id(rt)}-{o}", o) + od_invariant(o, res))
            for name, o, when, then, desc in invs:
                L += [f"Invariant: {name}",
                      f"Description: {q(od_title(res.od(o)) + ': ' + desc)}",
                      "Severity: #error",
                      f"Expression: {q(when + ' implies (' + then + ')')}", ""]

        m["invariants"] = invs
        closed = [e for e in cfg["elements"] if e not in m["elements"] and e not in cfg["keep"]]
        m["closed"] = closed
        L += [f"Profile: {profile_name(rt)}", f"Parent: {rt}", f"Id: {profile_id(rt)}",
              f'Title: "{rt} (SAN KPI)"',
              f'Description: "The one {rt} profile of the model, generated from the KPI and dataset definitions.'
              + (f' Allowed codes: {code_vs_name(rt)}.' if cfg["code"] else "") + ' Elements nothing asks for are closed."',
              "* ^status = #draft"]
        if cfg["code"]:
            L.append(f"* {cfg['code']} from {code_vs_name(rt)} (required)")
        if cfg.get("subject", True):
            L += ["* subject 1..1", "* subject only Reference(Patient)"]
        L += [f"* {e} 0..0" for e in closed]
        L += [f"* obeys {name}" for name, *_ in invs]
        L.append("")
    return "\n".join(L)


def is_code_param(name):
    return name == "code" or name.startswith("code:")


def rolled_up_filters(res, criteria):
    """Resolved _typeFilter strings. Criteria on the same resource that differ only in their code
    parameter become one filter with the codes as a comma-separated list (FHIR search: OR)."""
    groups = {}
    for c in criteria:
        params = [(p["name"], res.value(p["value"])) for p in c.get("param", [])]
        codes = [(n, v) for n, v in params if is_code_param(n)]
        if len(codes) == 1:
            name, value = codes[0]
            others = tuple((n, v) for n, v in params if not is_code_param(n))
            g = groups.setdefault((c["resource"], name, others), [])
            for v in value.split(","):
                if v not in g:
                    g.append(v)
        else:
            groups.setdefault((c["resource"], None, tuple(params)), [])
    out = []
    for (resource, code_name, others), values in groups.items():
        parts = ([f"{code_name}={','.join(values)}"] if code_name else []) + [f"{n}={v}" for n, v in others]
        out.append(resource + ("?" + "&".join(parts) if parts else ""))
    return out


def exports(defs, res, ds):
    """Resolved export request of one dataset: Group filters and Parameters."""
    cohort = [res.query(c) for c in ds["cohort"]["criteria"]]
    types, elements, criteria = [], [], []
    sources = []
    for kid in ds["kpi"]:
        kpi = defs["kpi"].get(kid)
        if not kpi:
            raise DefinitionError(f"Dataset '{ds['id']}': KPI '{kid}' is not defined")
        sources += kpi["criteria"]
    sources += ds.get("include", [])  # data the dataset releases outside any KPI
    for c in sources:
        if c["resource"] not in types:
            types.append(c["resource"])
        criteria.append(c)
        for e in c.get("element", []):
            item = f"{c['resource']}.{e}"
            if item not in elements:
                elements.append(item)
    return dict(cohort=cohort, types=types, filters=rolled_up_filters(res, criteria), elements=elements)


def gen_exports_fsh(defs, res):
    L = [f"// {HEADER}", ""]
    for ds in defs["dataset"].values():
        x = exports(defs, res, ds)
        i = ds["id"]
        L += [f"Instance: {i}-cohort", "InstanceOf: Group", "Usage: #definition",
              f'Title: "{ds["title"]} cohort (generated)"',
              f'Description: "Cohort of the {ds["title"]} dataset as bulk-data member-filters."',
              "* type = #person", "* actual = true", f"* name = {q(ds['title'] + ' cohort')}"]
        for expr in x["cohort"]:
            L += [f"* modifierExtension[+].url = {q(MEMBER_FILTER_URL)}",
                  "* modifierExtension[=].valueExpression.language = #application/x-fhir-query",
                  f"* modifierExtension[=].valueExpression.expression = {q(expr)}"]
        L += ["", f"Instance: {i}-export", "InstanceOf: Parameters", "Usage: #definition",
              f'Title: "{ds["title"]} export parameters (generated)"',
              f'Description: "_type, _typeFilter and _elements of the {ds["title"]} export."',
              "* parameter[+].name = \"_type\"", f"* parameter[=].valueString = {q(','.join(x['types']))}"]
        for f in x["filters"]:
            L += ["* parameter[+].name = \"_typeFilter\"", f"* parameter[=].valueString = {q(f)}"]
        L += ["* parameter[+].name = \"_elements\"", f"* parameter[=].valueString = {q(','.join(x['elements']))}", ""]
    return "\n".join(L)


