def ext_link(res, v):
    """Markdown link for a ValueSet reference: a local ValueSet page, or the pinned external canonical."""
    if v in res.defs["vs"]:
        return f"[{v}](ValueSet-{v}.html)"
    url = res.vs_url(v).split("|")[0]
    return f"[{vs_label(res, v) if is_url(v) else v}]({url})"


def gen_external_section(res):
    if not res.external:
        return []
    L = ["---", "", "### External ValueSets", "",
         "Maintained outside this repository and pinned here. `_syncValueSets.py check` compares each pin with its source.", "",
         "| Key | Source | Pinned version | Mode |", "|---|---|---|---|"]
    for k, e in res.external.items():
        mode = "downloaded in the build" if e["mode"] == "download" else "reference only (not downloadable)"
        L.append(f"| [{k}]({e['canonical']}) | {e['source']} | {e.get('version') or 'not versioned (implicit)'} | {mode} |")
    return L + [""]


