def group_of(defs, ds):
    """The data requirement that selects the patients of the dataset's Group."""
    gid = ds.get("group")
    r = defs["req"].get(gid)
    if not r:
        raise DefinitionError(f"Dataset '{ds['id']}': group requirement '{gid}' is not defined")
    return r


def requirements_of(defs, ds):
    """The data requirements the dataset lists (not expanded; see dataset_requirements)."""
    out = []
    for rid in ds.get("requirement", []):
        r = defs["req"].get(rid)
        if not r:
            raise DefinitionError(f"Dataset '{ds['id']}': data requirement '{rid}' is not defined")
        out.append(r)
    return out


def expand(defs, r, _path=()):
    """A data requirement together with the requirements it builds on (`requirement`, recursively):
    the bases first, the requirement itself last, each once."""
    if r["id"] in _path:
        raise DefinitionError("Data requirements refer to each other in a cycle: " + " -> ".join(_path + (r["id"],)))
    out = []
    for rid in r.get("requirement", []):
        base = defs["req"].get(rid)
        if not base:
            raise DefinitionError(f"Data requirement '{r['id']}': requirement '{rid}' is not defined")
        for k in expand(defs, base, _path + (r["id"],)):
            if all(k["id"] != o["id"] for o in out):
                out.append(k)
    if not r.get("criteria") and not out:
        raise DefinitionError(f"Data requirement '{r['id']}' has no criteria and builds on no other requirement")
    return out + [r]


def criteria_of(defs, r):
    """Every criterion of a data requirement: its own and those of the requirements it builds on."""
    return [c for k in expand(defs, r) for c in k.get("criteria", [])]


def post_filters_of(defs, r):
    """Every postFilter of a data requirement, paired with the requirement that states it."""
    return [(k, p) for k in expand(defs, r) for p in k.get("postFilter", [])]


def dataset_requirements(defs, ds):
    """Every data requirement whose data the dataset releases: the listed ones and the ones they
    build on, each once."""
    out = []
    for r in requirements_of(defs, ds):
        for k in expand(defs, r):
            if all(k["id"] != o["id"] for o in out):
                out.append(k)
    return out


# ---------------------------------------------------------------------------
# Deriving the model of one dataset from its data requirements
# ---------------------------------------------------------------------------
def derive_model(defs, res, ds):
    model = {}
    res.answers = {}
    res.ds = ds["id"]

    def absorb(c, owner, owner_id):
        rt = c["resource"]
        if rt not in RESOURCES:
            raise DefinitionError(f"{owner}: resource {rt} has no generated profile (supported: {', '.join(RESOURCES)})")
        m = model.setdefault(rt, dict(ods=[], vss=[], codes=[], qs=[], elements=[], reqs=[]))
        for qid in questionnaire_sources(c):
            res.q_url(qid)  # fails early when the questionnaire is not defined
            if qid not in m["qs"]:
                m["qs"].append(qid)
        ods, vss, codes = code_sources(c)
        for code in codes:
            if code not in m["codes"]:
                m["codes"].append(code)
        a_vss, a_codes = answer_sources(c)
        for o in ods:
            res.od(o)
            if o not in m["ods"]:
                m["ods"].append(o)
            if a_vss or a_codes:  # answers a criterion adds to this measurement
                a = res.answers.setdefault(o, dict(vss=[], codes=[]))
                for v in a_vss:
                    res.vs_url(v)
                    if v not in a["vss"]:
                        a["vss"].append(v)
                for code in a_codes:
                    if code not in a["codes"]:
                        a["codes"].append(code)
        for v in vss:
            res.vs_url(v)
            if v not in m["vss"]:
                m["vss"].append(v)
        for e in c.get("element", []):
            if e not in RESOURCES[rt]["elements"]:
                raise DefinitionError(f"{owner}: '{e}' is not a top-level element of {rt}")
            if e not in m["elements"]:
                m["elements"].append(e)
        if owner_id not in m["reqs"]:
            m["reqs"].append(owner_id)

    for r in dataset_requirements(defs, ds):
        for c in r.get("criteria", []):
            absorb(c, f"Data requirement '{r['id']}'", r["id"])
    for c in ds.get("include", []):  # data the dataset releases outside any requirement
        absorb(c, f"Dataset '{ds['id']}'", ds["id"])
    model["_answers"] = res.answers
    return model


def resources_of(model):
    return {rt: m for rt, m in model.items() if not rt.startswith("_")}


def base_cardinality(defs, rt):
    """{top-level element: (min, max)} as the hand-written SAN profile constrains it (its differential),
    or None when there is no such profile."""
    base = RESOURCES[rt]["base"]
    sd = next((p for p in defs["profile"].values() if p.get("name") == base), None)
    if sd is None:
        return None
    out = {}
    for e in sd.get("differential", {}).get("element", []):
        path = e.get("path", "")
        if path.count(".") == 1 and ":" not in e.get("id", ""):
            name = path.split(".", 1)[1]
            lo, hi = out.get(name, (None, None))
            out[name] = (e.get("min", lo), e.get("max", hi))
    return out


def closed_in_base(defs, rt):
    card = base_cardinality(defs, rt)
    return None if card is None else {e for e, (_, hi) in card.items() if hi == "0"}


def required_in_base(defs, rt):
    card = base_cardinality(defs, rt) or {}
    return {e for e, (lo, _) in card.items() if lo and lo > 0}


def check_against_base(defs, ds, model):
    """Warn for every element a dataset asks for that its SAN profile does not allow.

    The generated profile derives from the SAN profile, so such an element can never be
    exported: it has to be modelled in the SAN profile (and against nl-core) first."""
    warnings = []
    for rt, m in model.items():
        base = RESOURCES[rt]["base"]
        closed = closed_in_base(defs, rt)
        if closed is None:
            warnings.append(f"{ds['id']}: {rt} has no SAN profile '{base}' in input/fsh/fhir/")
            continue
        for e in m["elements"]:
            if e in closed:
                warnings.append(f"{ds['id']}: asks for {rt}.{e}, but {base} excludes it (0..0). "
                                f"Model it in {base} first; it cannot be exported as long as it is closed there.")
    return warnings


def vs_label(res, vs_id):
    """Short display name for a ValueSet reference: the registry key when there is one."""
    if is_url(vs_id):
        for k, e in res.external.items():
            if unpinned(e["canonical"]) == unpinned(vs_id):
                return k
    return vs_id


