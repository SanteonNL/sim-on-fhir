def wrap_query(q, prefix):
    """A FHIR query on several lines: the resource and its first parameter, then one '&parameter' per line."""
    parts = re.split(r"&", q)
    pad = " " * (len(prefix) + len(parts[0].split("?")[0]))
    return [prefix + parts[0]] + [pad + "&" + p for p in parts[1:]]


