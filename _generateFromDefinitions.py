def sushi_config_value(key):
    m = re.search(rf"^{key}:\s*(.+?)\s*$", (ROOT / "sushi-config.yaml").read_text(encoding="utf-8"), re.M)
    if not m:
        raise DefinitionError(f"{key} not found in sushi-config.yaml")
    return m.group(1).strip("\"'")


def compile_definitions():
    sushi = shutil.which("sushi")
    if not sushi:
        raise DefinitionError("SUSHI not found on PATH (npm install -g fsh-sushi)")
    tmp = Path(tempfile.mkdtemp(prefix="defs-"))
    # The whole FSH tree (minus generated/) with the real config, so value sets, profiles and
    # logical models defined next to the definitions resolve.
    shutil.copytree(FSH_DIR, tmp / "input" / "fsh", ignore=shutil.ignore_patterns("generated"))
    cfg = (ROOT / "sushi-config.yaml").read_text(encoding="utf-8")
    (tmp / "sushi-config.yaml").write_text(cfg.rstrip() + "\nFSHOnly: true\n", encoding="utf-8")
    res = subprocess.run([sushi, "build", str(tmp)], capture_output=True, text=True)
    if res.returncode != 0:
        raise DefinitionError("SUSHI failed on the definitions:\n" + res.stdout + res.stderr)
    return tmp


def load(tmp):
    out = dict(od={}, vs={}, kpi={}, dataset={})
    for f in sorted((tmp / "fsh-generated" / "resources").glob("*.json")):
        r = json.loads(f.read_text(encoding="utf-8"))
        rt = r.get("resourceType", "")
        if rt == "ObservationDefinition":
            out["od"][r["id"]] = r
        elif rt == "ValueSet":
            out["vs"][r["id"]] = r
        elif rt.endswith("/kpi-definition"):
            out["kpi"][r["id"]] = r
        elif rt.endswith("/dataset-definition"):
            out["dataset"][r["id"]] = r
    return out


# ---------------------------------------------------------------------------
# Resolving {od:...} / {vs:...} references
# ---------------------------------------------------------------------------
def coding_tokens(cc):
    return [f"{c['system']}|{c['code']}" for c in cc.get("coding", [])]


def vs_ref_id(od):
    ref = od.get("validCodedValueSet", {}).get("reference", "")
    return ref if is_url(ref) else (ref.split("/")[-1] if ref else None)


class Resolver:
    def __init__(self, defs):
        self.defs = defs
        self.canonical = sushi_config_value("canonical")
        self.external = load_external()
        self.answers = {}  # od id -> answers added by KPI criteria (filled by derive_model)

    def vs_url(self, vs_id):
        ext = self.external
        if vs_id in self.defs["vs"]:
            pass
        elif vs_id in ext:  # maintained elsewhere (ART-DECOR, NTS): resolved to its pinned version
            return pinned_ref(ext[vs_id])
        elif is_url(vs_id):  # unregistered canonical: used as written
            for e in ext.values():
                if unpinned(e["canonical"]) == unpinned(vs_id):
                    return pinned_ref(e)
            return vs_id
        vs = self.defs["vs"].get(vs_id)
        if not vs:
            raise DefinitionError(f"ValueSet '{vs_id}' is not defined in the definitions")
        return vs.get("url") or f"{self.canonical}/ValueSet/{vs_id}"

    def od(self, od_id):
        od = self.defs["od"].get(od_id)
        if not od:
            raise DefinitionError(f"ObservationDefinition '{od_id}' is not defined in the definitions")
        return od

    def one(self, kind, body):
        if kind == "vs":
            return self.vs_url(body)
        od_id, _, attr = body.partition(".")
        od = self.od(od_id)
        if attr == "code":
            return ",".join(coding_tokens(od["code"]))
        if attr == "unit":
            return ",".join(coding_tokens(od["quantitativeDetails"]["unit"]))
        if attr == "valid":
            vs_id = vs_ref_id(od)
            if not vs_id:
                raise DefinitionError(f"ObservationDefinition '{od_id}' has no validCodedValueSet")
            return self.vs_url(vs_id)
        raise DefinitionError(f"Unknown reference {{od:{body}}} (use .code, .unit or .valid)")

    def value(self, value):
        return REF.sub(lambda m: self.one(m.group(1), m.group(2)), value)

    def query(self, criterion):
        params = [f"{p['name']}={self.value(p['value'])}" for p in criterion.get("param", [])]
        return criterion["resource"] + ("?" + "&".join(params) if params else "")


def code_sources(criterion):
    """(od ids, vs ids or URLs, literal (system, code) pairs) behind a criterion's code parameter(s).

    A code parameter may reference a definition ({od:..}, {vs:..}), name an external
    value set by URL (code:in=http://...), or list literal system|code tokens.
    """
    ods, vss, codes = [], [], []
    for p in criterion.get("param", []):
        if p["name"] == "code" or p["name"].startswith("code:"):
            for kind, body in REF.findall(p["value"]):
                (ods if kind == "od" else vss).append(body.split(".")[0] if kind == "od" else body)
            for tok in REF.sub("", p["value"]).split(","):
                tok = tok.strip()
                if not tok:
                    continue
                if p["name"].endswith(":in") and is_url(tok):
                    vss.append(tok)
                elif "|" in tok:
                    system, _, code = tok.partition("|")
                    codes.append((system, code))
    return ods, vss, codes


def answer_sources(criterion):
    """(value set ids or URLs, literal (system, code) pairs) a criterion adds as permitted answers.

    Read from value-concept parameters: `value-concept=system|code,...` lists answers inline,
    `value-concept:in={vs:..}` or a URL names a value set (local, ART-DECOR or NTS).
    """
    vss, codes = [], []
    for p in criterion.get("param", []):
        if p["name"] == "value-concept" or p["name"].startswith("value-concept:"):
            vss += [body for kind, body in REF.findall(p["value"]) if kind == "vs"]
            for tok in REF.sub("", p["value"]).split(","):
                tok = tok.strip()
                if p["name"].endswith(":in") and is_url(tok):
                    vss.append(tok)
                elif "|" in tok:
                    system, _, code = tok.partition("|")
                    codes.append((system, code))
    return vss, codes


def lower_first(s):
    return s[:1].lower() + s[1:]


# Names of generated artifacts follow the HL7 Europe / EHDS pattern: a camelCase resource name,
# a family suffix (-san) and a use-case suffix (-kpi); titles read "Resource (SAN KPI)".
def profile_name(rt):
    return f"{rt}SanKpi"


def profile_id(rt):
    return f"{lower_first(rt)}-san-kpi"


def code_vs_name(rt):
    return f"{rt}CodeSanKpi"


def code_vs_id(rt):
    return f"{lower_first(rt)}Code-san-kpi"


def answer_vs_id(od_id):
    return f"answers-{od_id}-san-kpi"


