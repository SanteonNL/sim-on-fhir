REF = re.compile(r"\{(od|vs):([^}]+)\}")


TODAY = re.compile(r"\{today(?:([+-])(\d+)([dmy]))?\}")


def fill_today(text, today):
    """Replace {today}, {today-18y}, {today+3m}, {today-90d} by a concrete date (the exporter does this per run)."""
    import calendar
    import datetime

    def one(m):
        if not m.group(1):
            return today.isoformat()
        n = int(m.group(2)) * (1 if m.group(1) == "+" else -1)
        unit = m.group(3)
        if unit == "d":
            return (today + datetime.timedelta(days=n)).isoformat()
        months = n * (12 if unit == "y" else 1)
        y, mo = divmod(today.year * 12 + today.month - 1 + months, 12)
        day = min(today.day, calendar.monthrange(y, mo + 1)[1])
        return datetime.date(y, mo + 1, day).isoformat()

    return TODAY.sub(one, text)


def is_url(s):
    return s.startswith(("http://", "https://"))


def unpinned(canonical):
    return canonical.split("|")[0].split("--")[0]


def load_external():
    """ValueSets maintained outside the repo (see _syncValueSets.py), by key."""
    sys.path.insert(0, str(ROOT))
    from _syncValueSets import load  # the manifest reader lives with the sync script
    return {e["key"]: e for e in load()["valuesets"]}


def pinned_ref(entry):
    """The canonical a profile or query must use: the pinned version of an external ValueSet."""
    if entry["source"] == "decor" or not entry.get("version"):
        return entry["canonical"]
    return f"{entry['canonical']}|{entry['version']}"


class DefinitionError(Exception):
    pass


